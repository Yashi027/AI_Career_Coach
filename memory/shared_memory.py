"""
Shared Memory
It will act as a common storage for all agents.
Responsibilities:
- Store information generated by ai agents
- Retrieve information for downstream agents
- Provide a common communication mechanism
- Remain independent of any specific agent or service
"""

from typing import Any

class SharedMemory:
    "Share memory accessible by every agent"
    def __init__(self):
        self._memory : dict[str, Any] = {}

    def add(self, key: str, value: Any) -> None:
        " Store Data "
        self._memory[key] = value

    def get(self, key: str) -> str:
        " Retrieve Data "
        return self._memory.get(key)

    def remove(self, key: str) -> None:
        " Remove Data "
        if key in self._memory:
            del self._memory[key]

    def exists(self, key: str) -> bool:
        " Check if key exists "
        return key in self._memory

    def clear(self) -> None:
        " Clear Memory "
        self._memory.clear()

    def get_all(self) -> dict[str, Any]:
        " Get All Memory "
        return self._memory

    def display(self) -> None:
        " Print Current Memory "
        print("="*25)
        for key, val in self._memory.items():
            print(key)
            print(val)
            print("="*25)
            