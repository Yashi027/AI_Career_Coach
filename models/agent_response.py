"""
Agent Response Model
Represents the standardized response returned by the every AI agent
"""

from dataclasses import dataclass, field
from typing import Optional
from datetime import datetime


@dataclass
class AgentResponse:
    "Standard response returned by every AI agent"
    agent_name: str                                            # Name of the agent that generated the response
    output: str                                                # The output generated by the agent
    status: str = "SUCCESS"                                    # Execution Status of the response
    error: Optional[str] = None                                # Error message if the status is ERROR
    timestamp: datetime = field(default_factory=datetime.now)  # Timestamp of the response

    def is_success(self) -> bool:
        """Check if the response status is SUCCESS"""
        return self.status.upper() == "SUCCESS"

    def __str__(self):
        """Pretty string representation"""
        return f"""\n AgentResponse(
            agent_name={self.agent_name}, 
            status={self.status}, 
            timestamp={self.timestamp}, 
            output={self.output}
        )"""